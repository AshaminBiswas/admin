/**
 * Pre-computed Set of NCR PIN codes for O(1) instantaneous lookup.
 */
const ncrPinSet = new Set<number>(NCR_PIN_CODES.pinCodes);

/**
 * Checks whether a given 6-digit PIN code falls inside the official NCR boundary.
 * Accepts string (e.g. "110001") or number (110001).
 */
export function isNcrPinCode(pin: string | number | null | undefined): boolean {
  if (!pin) return false;
  const num = typeof pin === 'number' ? pin : parseInt(String(pin).trim(), 10);
  if (isNaN(num)) return false;
  return ncrPinSet.has(num);
}

/**
 * Returns total count of recognized NCR PIN codes.
 */
export function getNcrPinCodeCount(): number {
  return ncrPinSet.size;
}
